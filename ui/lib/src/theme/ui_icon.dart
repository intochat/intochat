final Map<String, IconData> _catalogLookup = <String, IconData>{
  for (final entry in uiIconCatalog) entry.slug: entry.icon,
};

/// Normalizes raw icon identifiers (trimming, case folding, converting
/// `camelCase` or `snake_case` to `kebab-case`) before lookup.
String _normalizeIconName(String raw) {
  final trimmed = raw.trim();
  if (trimmed.isEmpty) return '';
  final kebab = trimmed
      .replaceAllMapped(
        RegExp(r'([a-z0-9])([A-Z])'),
        (m) => '${m.group(1)}-${m.group(2)}',
      )
      .replaceAll(RegExp(r'[_\s]+'), '-')
      .toLowerCase();
  return kebab;
}

/// Lucide glyph for a Figma / `Kit.Icons` / catalogue icon name, or null when unknown.
