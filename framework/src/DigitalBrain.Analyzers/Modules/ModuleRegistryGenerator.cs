using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace DigitalBrain.Analyzers.Modules;

/// <summary>
/// Compile-time module discovery generator.
/// <list type="bullet">
/// <item>Emits <c>[assembly: RegisteredModule(typeof(...))]</c> for every concrete public <c>[Module]</c> class declared in the current assembly.</item>
/// <item>Implements any <c>static partial IReadOnlyList&lt;Type&gt;</c> method decorated with <c>[GeneratedModuleRegistry]</c>
/// with every accessible concrete public <c>[Module]</c> class from the current assembly and all referenced assemblies.</item>
/// </list>
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class ModuleRegistryGenerator : IIncrementalGenerator
{
    private const string ModuleBaseMetadataName = "DigitalBrain.Modules.Module";
    private const string ModuleAttributeMetadataName = "DigitalBrain.Modules.ModuleAttribute";
    private const string GeneratedModuleRegistryAttributeMetadataName = "DigitalBrain.Modules.GeneratedModuleRegistryAttribute";
    private const string RegisteredModuleAttributeMetadataName = "DigitalBrain.Modules.RegisteredModuleAttribute";
    private const string DigitalBrainAssemblyName = "DigitalBrain";

    private static readonly SymbolDisplayFormat FullTypeFormat = new(
        globalNamespaceStyle: SymbolDisplayGlobalNamespaceStyle.Included,
        typeQualificationStyle: SymbolDisplayTypeQualificationStyle.NameAndContainingTypesAndNamespaces,
        genericsOptions: SymbolDisplayGenericsOptions.None,
        miscellaneousOptions: SymbolDisplayMiscellaneousOptions.EscapeKeywordIdentifiers);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var assemblyModules = context.CompilationProvider.Select(static (compilation, ct) =>
        {
            var moduleBase = compilation.GetTypeByMetadataName(ModuleBaseMetadataName);
            var moduleAttr = compilation.GetTypeByMetadataName(ModuleAttributeMetadataName);
            var registeredAttr = compilation.GetTypeByMetadataName(RegisteredModuleAttributeMetadataName);
            if (moduleBase is null || moduleAttr is null || registeredAttr is null)
            {
                return EquatableArray<string>.Empty;
            }

            var found = new List<string>();
            CollectModules(compilation, compilation.Assembly, moduleBase, moduleAttr, found, ct);
            found.Sort(StringComparer.Ordinal);
            return new EquatableArray<string>(found.Distinct(StringComparer.Ordinal).ToImmutableArray());
        });

        context.RegisterSourceOutput(assemblyModules, static (spc, modules) =>
        {
            if (modules.Length == 0)
            {
                return;
            }

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("#nullable enable");
            foreach (var typeName in modules)
            {
                sb.Append("[assembly: global::").Append(RegisteredModuleAttributeMetadataName).Append("(typeof(").Append(typeName).AppendLine("))]");
            }

            spc.AddSource("RegisteredModules.g.cs", sb.ToString());
        });

        var registryTargets = context.SyntaxProvider.ForAttributeWithMetadataName(
                GeneratedModuleRegistryAttributeMetadataName,
                static (node, _) => node is MethodDeclarationSyntax,
                static (ctx, ct) => ExtractTarget(ctx, ct))
            .Where(static target => target is not null)
            .Select(static (target, _) => target!)
            .Collect();

        var allDiscoveredModules = context.CompilationProvider.Select(static (compilation, ct) =>
        {
            var moduleBase = compilation.GetTypeByMetadataName(ModuleBaseMetadataName);
            var moduleAttr = compilation.GetTypeByMetadataName(ModuleAttributeMetadataName);
            if (moduleBase is null || moduleAttr is null)
            {
                return EquatableArray<string>.Empty;
            }

            var found = new List<string>();
            CollectModules(compilation, compilation.Assembly, moduleBase, moduleAttr, found, ct);

            var seenAssemblies = new HashSet<string>(StringComparer.Ordinal)
            {
                compilation.Assembly.Name,
            };

            foreach (var referenced in compilation.SourceModule.ReferencedAssemblySymbols)
            {
                ct.ThrowIfCancellationRequested();
                if (!seenAssemblies.Add(referenced.Name))
                {
                    continue;
                }

                if (!ReferencesDigitalBrain(referenced))
                {
                    continue;
                }

                CollectModules(compilation, referenced, moduleBase, moduleAttr, found, ct);
            }

            found.Sort(StringComparer.Ordinal);
            return new EquatableArray<string>(found.Distinct(StringComparer.Ordinal).ToImmutableArray());
        });

        context.RegisterSourceOutput(
            registryTargets.Combine(allDiscoveredModules),
            static (spc, pair) => EmitRegistries(spc, pair.Left, pair.Right));
    }

    private static RegistryTarget? ExtractTarget(GeneratorAttributeSyntaxContext ctx, System.Threading.CancellationToken ct)
    {
        ct.ThrowIfCancellationRequested();
        if (ctx.TargetSymbol is not IMethodSymbol method)
        {
            return null;
        }

        if (!method.IsStatic || !method.IsPartialDefinition || method.Parameters.Length != 0 || method.TypeParameters.Length != 0)
        {
            return null;
        }

        if (method.ContainingType is not { } containingType)
        {
            return null;
        }

        var ns = containingType.ContainingNamespace is { IsGlobalNamespace: false } n
            ? n.ToDisplayString()
            : null;

        var containers = new List<TypeContainer>();
        for (var current = containingType; current is not null; current = current.ContainingType)
        {
            var kind = current.TypeKind switch
            {
                TypeKind.Struct => current.IsRecord ? "record struct" : "struct",
                TypeKind.Class => current.IsRecord ? "record class" : "class",
                _ => null,
            };
            if (kind is null)
            {
                return null;
            }

            containers.Add(new TypeContainer(kind, current.Name));
        }

        containers.Reverse();

        var accessibility = method.DeclaredAccessibility switch
        {
            Accessibility.Public => "public",
            Accessibility.Internal => "internal",
            Accessibility.Protected => "protected",
            Accessibility.ProtectedOrInternal => "protected internal",
            Accessibility.ProtectedAndInternal => "private protected",
            _ => "private",
        };

        return new RegistryTarget(ns, new EquatableArray<TypeContainer>(containers.ToImmutableArray()), accessibility, method.Name);
    }

    private static void EmitRegistries(
        SourceProductionContext spc,
        ImmutableArray<RegistryTarget> targets,
        EquatableArray<string> modules)
    {
        if (targets.IsDefaultOrEmpty)
        {
            return;
        }

        for (var i = 0; i < targets.Length; i++)
        {
            var target = targets[i];
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("#nullable enable");
            if (target.Namespace is not null)
            {
                sb.Append("namespace ").Append(target.Namespace).AppendLine(";");
                sb.AppendLine();
            }

            var indent = 0;
            foreach (var container in target.Containers)
            {
                Indent(sb, indent);
                sb.Append("partial ").Append(container.Kind).Append(' ').AppendLine(container.Name);
                Indent(sb, indent);
                sb.AppendLine("{");
                indent++;
            }

            Indent(sb, indent);
            sb.Append(target.Accessibility)
                .Append(" static partial global::System.Collections.Generic.IReadOnlyList<global::System.Type> ")
                .Append(target.MethodName)
                .Append("() => __GeneratedModuleRegistry_")
                .Append(target.MethodName)
                .AppendLine("_Holder.Types;");
            sb.AppendLine();

            Indent(sb, indent);
            sb.Append("private static class __GeneratedModuleRegistry_").Append(target.MethodName).AppendLine("_Holder");
            Indent(sb, indent);
            sb.AppendLine("{");
            Indent(sb, indent + 1);
            sb.AppendLine("internal static readonly global::System.Type[] Types =");
            Indent(sb, indent + 1);
            sb.AppendLine("[");
            foreach (var typeName in modules)
            {
                Indent(sb, indent + 2);
                sb.Append("typeof(").Append(typeName).AppendLine("),");
            }

            Indent(sb, indent + 1);
            sb.AppendLine("];");
            Indent(sb, indent);
            sb.AppendLine("}");

            while (indent > 0)
            {
                indent--;
                Indent(sb, indent);
                sb.AppendLine("}");
            }

            var hintPrefix = string.Join("_", target.Containers.Select(static c => c.Name));
            var hintName = targets.Length == 1
                ? $"{hintPrefix}.{target.MethodName}.g.cs"
                : $"{hintPrefix}.{target.MethodName}_{i}.g.cs";
            spc.AddSource(hintName, sb.ToString());
        }
    }

    private static void Indent(StringBuilder sb, int level)
    {
        for (var i = 0; i < level; i++)
        {
            sb.Append("    ");
        }
    }

    private static bool ReferencesDigitalBrain(IAssemblySymbol assembly)
    {
        if (string.Equals(assembly.Name, DigitalBrainAssemblyName, StringComparison.Ordinal))
        {
            return true;
        }

        foreach (var module in assembly.Modules)
        {
            foreach (var reference in module.ReferencedAssemblies)
            {
                if (string.Equals(reference.Name, DigitalBrainAssemblyName, StringComparison.Ordinal))
                {
                    return true;
                }
            }
        }

        return false;
    }

    private static void CollectModules(
        Compilation compilation,
        IAssemblySymbol assembly,
        INamedTypeSymbol moduleBase,
        INamedTypeSymbol moduleAttr,
        List<string> results,
        System.Threading.CancellationToken ct)
    {
        var namespaces = new Stack<INamespaceSymbol>();
        namespaces.Push(assembly.GlobalNamespace);
        while (namespaces.Count > 0)
        {
            ct.ThrowIfCancellationRequested();
            var ns = namespaces.Pop();
            foreach (var childNs in ns.GetNamespaceMembers())
            {
                namespaces.Push(childNs);
            }

            foreach (var type in ns.GetTypeMembers())
            {
                VisitType(compilation, type, moduleBase, moduleAttr, results, ct);
            }
        }
    }

    private static void VisitType(
        Compilation compilation,
        INamedTypeSymbol type,
        INamedTypeSymbol moduleBase,
        INamedTypeSymbol moduleAttr,
        List<string> results,
        System.Threading.CancellationToken ct)
    {
        ct.ThrowIfCancellationRequested();
        if (type.DeclaredAccessibility != Accessibility.Public)
        {
            return;
        }

        if (IsConcreteProductModule(compilation, type, moduleBase, moduleAttr))
        {
            results.Add(type.ToDisplayString(FullTypeFormat));
        }

        foreach (var nested in type.GetTypeMembers())
        {
            VisitType(compilation, nested, moduleBase, moduleAttr, results, ct);
        }
    }

    private static bool IsConcreteProductModule(
        Compilation compilation,
        INamedTypeSymbol type,
        INamedTypeSymbol moduleBase,
        INamedTypeSymbol moduleAttr)
    {
        if (type.TypeKind != TypeKind.Class || type.IsAbstract || type.IsStatic || type.Arity != 0)
        {
            return false;
        }

        if (!compilation.IsSymbolAccessibleWithin(type, compilation.Assembly))
        {
            return false;
        }

        if (!InheritsFrom(type, moduleBase))
        {
            return false;
        }

        if (!HasAttribute(type, moduleAttr))
        {
            return false;
        }

        foreach (var ctor in type.InstanceConstructors)
        {
            if (ctor.Parameters.Length == 0 && ctor.DeclaredAccessibility == Accessibility.Public)
            {
                return true;
            }
        }

        return false;
    }

    private static bool InheritsFrom(INamedTypeSymbol type, INamedTypeSymbol baseType)
    {
        for (var current = type.BaseType; current is not null; current = current.BaseType)
        {
            if (SymbolEqualityComparer.Default.Equals(current, baseType))
            {
                return true;
            }
        }

        return false;
    }

    private static bool HasAttribute(INamedTypeSymbol type, INamedTypeSymbol attributeType)
    {
        foreach (var attribute in type.GetAttributes())
        {
            if (SymbolEqualityComparer.Default.Equals(attribute.AttributeClass, attributeType))
            {
                return true;
            }
        }

        return false;
    }

    private sealed class TypeContainer(string kind, string name) : IEquatable<TypeContainer>
    {
        public string Kind { get; } = kind;
        public string Name { get; } = name;

        public bool Equals(TypeContainer? other)
            => other is not null
                && string.Equals(Kind, other.Kind, StringComparison.Ordinal)
                && string.Equals(Name, other.Name, StringComparison.Ordinal);

        public override bool Equals(object? obj) => Equals(obj as TypeContainer);

        public override int GetHashCode()
            => unchecked((StringComparer.Ordinal.GetHashCode(Kind) * 397) ^ StringComparer.Ordinal.GetHashCode(Name));
    }

    private sealed class RegistryTarget(
        string? @namespace,
        EquatableArray<TypeContainer> containers,
        string accessibility,
        string methodName) : IEquatable<RegistryTarget>
    {
        public string? Namespace { get; } = @namespace;
        public EquatableArray<TypeContainer> Containers { get; } = containers;
        public string Accessibility { get; } = accessibility;
        public string MethodName { get; } = methodName;

        public bool Equals(RegistryTarget? other)
            => other is not null
                && string.Equals(Namespace, other.Namespace, StringComparison.Ordinal)
                && Containers.Equals(other.Containers)
                && string.Equals(Accessibility, other.Accessibility, StringComparison.Ordinal)
                && string.Equals(MethodName, other.MethodName, StringComparison.Ordinal);

        public override bool Equals(object? obj) => Equals(obj as RegistryTarget);

        public override int GetHashCode()
        {
            unchecked
            {
                var hash = Namespace is null ? 0 : StringComparer.Ordinal.GetHashCode(Namespace);
                hash = (hash * 397) ^ Containers.GetHashCode();
                hash = (hash * 397) ^ StringComparer.Ordinal.GetHashCode(Accessibility);
                hash = (hash * 397) ^ StringComparer.Ordinal.GetHashCode(MethodName);
                return hash;
            }
        }
    }

    private readonly struct EquatableArray<T>(ImmutableArray<T> array) : IEquatable<EquatableArray<T>>, IEnumerable<T>
        where T : IEquatable<T>
    {
        public static readonly EquatableArray<T> Empty = new(ImmutableArray<T>.Empty);

        private readonly ImmutableArray<T> _array = array;

        public int Length => _array.IsDefault ? 0 : _array.Length;

        public bool Equals(EquatableArray<T> other)
        {
            var left = _array.IsDefault ? ImmutableArray<T>.Empty : _array;
            var right = other._array.IsDefault ? ImmutableArray<T>.Empty : other._array;
            if (left.Length != right.Length)
            {
                return false;
            }

            for (var i = 0; i < left.Length; i++)
            {
                if (!left[i].Equals(right[i]))
                {
                    return false;
                }
            }

            return true;
        }

        public override bool Equals(object? obj) => obj is EquatableArray<T> other && Equals(other);

        public override int GetHashCode()
        {
            if (_array.IsDefaultOrEmpty)
            {
                return 0;
            }

            unchecked
            {
                var hash = 17;
                foreach (var item in _array)
                {
                    hash = (hash * 31) + item.GetHashCode();
                }

                return hash;
            }
        }

        public IEnumerator<T> GetEnumerator()
            => ((IEnumerable<T>)(_array.IsDefault ? ImmutableArray<T>.Empty : _array)).GetEnumerator();

        System.Collections.IEnumerator System.Collections.IEnumerable.GetEnumerator() => GetEnumerator();
    }
}
