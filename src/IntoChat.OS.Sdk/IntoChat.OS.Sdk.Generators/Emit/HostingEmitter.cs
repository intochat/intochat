using System.Text;
using IntoChat.OS.Sdk.Generators.Models;

namespace IntoChat.OS.Sdk.Generators;

// The module-to-hosting link and nothing else: behaviour stays in ModuleHosting<T> and the hand-written extensions.
internal static class HostingEmitter
{
    public static string Emit(HostingModel model)
    {
        var text = new StringBuilder();
        text.Append("// <auto-generated/>\n#nullable enable\n\n");
        if (model.Namespace is not null) { text.Append("namespace ").Append(model.Namespace).Append(";\n\n"); }
        text.Append("partial class ").Append(model.ClassName).Append(" : global::IntoChat.OS.Aspire.Hosting.ModuleHosting<").Append(model.ModuleType).Append(">\n{\n}\n\n");
        text.Append("public static partial class ").Append(ExtensionsName(model.ClassName)).Append("\n{\n}\n");
        return text.ToString();
    }

    private static string ExtensionsName(string hostingClass)
        => hostingClass.EndsWith("ModuleHosting", StringComparison.Ordinal)
            ? hostingClass.Substring(0, hostingClass.Length - "ModuleHosting".Length) + "HostingExtensions"
            : hostingClass + "Extensions";
}
