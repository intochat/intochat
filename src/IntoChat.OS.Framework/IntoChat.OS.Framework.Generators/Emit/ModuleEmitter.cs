using System.Text;
using IntoChat.OS.Framework.Generators.Models;

namespace IntoChat.OS.Framework.Generators;

// Emits names and shapes only; no attribute ever carries a value, so none can reach generated source.
internal static class ModuleEmitter
{
    public static string Emit(ModuleModel model)
    {
        var usings = new List<string>();
        string Name(string qualified) => Qualification.For(qualified, model.Namespace, usings);
        var schema = Name("IntoChat.OS.Framework.Modules.Platform.Integrations.IntegrationSchema");
        var moduleId = Name("IntoChat.OS.Framework.Modules.ModuleId");
        var services = Name("Microsoft.Extensions.DependencyInjection.IServiceCollection");
        var configuration = Name("Microsoft.Extensions.Configuration.IConfiguration");
        var argument = Name("System.ArgumentNullException");
        var priceLists = Name("IntoChat.OS.Framework.Modules.Metering.ModulePriceLists");
        var descriptor = Name("IntoChat.OS.Contracts.Compute.ExternalOperationDescriptor");
        var moduleServices = Name("IntoChat.OS.Framework.Modules.ModuleServices");
        var moduleServicesContract = Name("IntoChat.OS.Framework.Modules.IModuleServices");
        var contracts = model.ContractsAnchor is null ? null : Name(model.ContractsAnchor);
        var priceList = model.PriceListType is null ? null : Name(model.PriceListType);
        var assembly = Name("System.Reflection.Assembly");

        var text = new StringBuilder();
        text.Append("// <auto-generated/>\n#nullable enable\n\n");
        foreach (var line in usings.OrderBy(item => item, StringComparer.Ordinal)) { text.Append(line).Append('\n'); }
        if (usings.Count > 0) { text.Append('\n'); }
        if (model.Namespace is not null) { text.Append("namespace ").Append(model.Namespace).Append(";\n\n"); }
        text.Append("partial class ").Append(model.ClassName).Append("\n{\n");
        text.Append("    public ").Append(model.ClassName).Append("() : base(new ").Append(moduleId).Append("(\"").Append(model.Id).Append("\")) { }\n");

        if (contracts is not null)
        {
            text.Append("\n    public override ").Append(assembly).Append("? Contracts => typeof(").Append(contracts).Append(").Assembly;\n");
        }

        if (model.LicenseProduct is not null)
        {
            text.Append("\n    public override string? LicenseProduct => ").Append(Literal(model.LicenseProduct)).Append(";\n");
        }

        if (model.Integrations.Length > 0)
        {
            text.Append("\n    public static ").Append(schema).Append(" Integration { get; } = ").Append(Build(schema, model.Integrations[0])).Append(";\n");
        }

        // Discovery reads Integration and Integrations together, so the array holds only the other schemas.
        if (model.Integrations.Length > 1)
        {
            text.Append("\n    public static ").Append(schema).Append("[] Integrations { get; } = [\n");
            for (var i = 1; i < model.Integrations.Length; i++) { text.Append("        ").Append(Build(schema, model.Integrations[i])).Append(",\n"); }
            text.Append("    ];\n");
        }

        text.Append("\n    public override void ConfigureServices(").Append(services).Append(" services, ").Append(configuration).Append(" configuration)\n    {\n");
        text.Append("        ").Append(argument).Append(".ThrowIfNull(services);\n");
        if (priceList is not null)
        {
            text.Append("        ").Append(priceLists).Append(".AddModulePriceList<").Append(priceList)
                .Append(">(services, ").Append(Literal(model.Id)).Append(", [\n");
            foreach (var operation in model.ExternalOperations)
            {
                text.Append("            new ").Append(descriptor).Append("(")
                    .Append(Literal(operation.Name)).Append(", ").Append(Literal(operation.Integration)).Append(", ")
                    .Append(Literal(operation.Unit)).Append("),\n");
            }
            text.Append("        ]);\n");
        }
        text.Append("        OnConfigure(new ").Append(moduleServices).Append("(services, configuration, Id));\n    }\n");
        text.Append("\n    partial void OnConfigure(").Append(moduleServicesContract).Append(" services);\n");
        text.Append("}\n");
        return text.ToString();
    }

    private static string Build(string schema, IntegrationModel integration)
    {
        var text = new StringBuilder();
        text.Append(schema).Append(".For(").Append(Literal(integration.Id)).Append(", ").Append(Literal(integration.DisplayName)).Append(')');
        foreach (var field in integration.Secrets)
        {
            text.Append(field.Optional ? ".OffersSecret(" : ".RequiresSecret(").Append(Literal(field.Name)).Append(')');
        }
        foreach (var field in integration.Settings)
        {
            text.Append(field.Optional ? ".OffersSetting(" : ".RequiresSetting(").Append(Literal(field.Name)).Append(')');
        }
        return text.ToString();
    }

    internal static string Literal(string value)
    {
        var text = new StringBuilder("\"");
        foreach (var c in value)
        {
            switch (c)
            {
                case '\\': text.Append("\\\\"); break;
                case '"': text.Append("\\\""); break;
                case '\n': text.Append("\\n"); break;
                case '\r': text.Append("\\r"); break;
                case '\t': text.Append("\\t"); break;
                default: text.Append(c); break;
            }
        }
        return text.Append('"').ToString();
    }
}
